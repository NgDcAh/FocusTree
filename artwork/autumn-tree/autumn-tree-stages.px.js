function leafCluster(x, y, sx, sy, shape, shadow, mid, light, gold) {
  const form = lobes[shape % lobes.length]
  const points = (scale, ox = 0, oy = 0) => form.flatMap(([px, py]) => [x + ox + px * sx * scale, y + oy + py * sy * scale])
  return [
    poly(points(1), shadow),
    poly(points(0.76, -0.8 * sx, -0.8 * sy), mid),
    poly(points(0.52, -1.0 * sx, -1.0 * sy), light),
  ]
}

